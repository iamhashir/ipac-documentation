import {mkdirSync, readFileSync, readdirSync, writeFileSync} from 'node:fs';
import {join, relative} from 'node:path';

const docsRoot = join(process.cwd(), 'docs');
const outputFile = join(process.cwd(), 'src/generated/documentationStatus.ts');

function walk(dir) {
  return readdirSync(dir, {withFileTypes: true}).flatMap((entry) => {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) {
      return walk(path);
    }
    return /\.(md|mdx)$/.test(entry.name) ? [path] : [];
  });
}

function readFrontMatter(source) {
  if (!source.startsWith('---\n')) {
    return {};
  }
  const end = source.indexOf('\n---\n', 4);
  if (end === -1) {
    return {};
  }
  return Object.fromEntries(
    source
      .slice(4, end)
      .split('\n')
      .map((line) => line.match(/^([^:]+):\s*(.*)$/))
      .filter(Boolean)
      .map((match) => [match[1].trim(), match[2].trim().replace(/^["']|["']$/g, '')]),
  );
}

function docId(file) {
  return relative(docsRoot, file).replace(/\.(md|mdx)$/, '');
}

function readStatusSources(statusTag) {
  const sourcesMatch = statusTag.match(/sources=\{\[([\s\S]*?)\]\}/);
  if (!sourcesMatch) {
    return [];
  }
  return Array.from(sourcesMatch[1].matchAll(/['"]([^'"]+)['"]/g)).map((match) => match[1]);
}

const docs = walk(docsRoot)
  .sort()
  .map((file) => {
    const source = readFileSync(file, 'utf8');
    const statusMatch = source.match(/<Status\s+[\s\S]*?type=["']([^"']+)["'][\s\S]*?>/);
    const dateMatch = statusMatch?.[0].match(/date=["']([^"']+)["']/);
    const frontMatter = readFrontMatter(source);

    if (!statusMatch) {
      throw new Error(`Missing <Status> on ${relative(process.cwd(), file)}`);
    }

    return {
      id: docId(file),
      title: frontMatter.title || docId(file),
      type: statusMatch[1],
      date: dateMatch?.[1] ?? null,
      sources: readStatusSources(statusMatch[0]),
    };
  });

const counts = docs.reduce(
  (acc, doc) => {
    acc[doc.type] = (acc[doc.type] ?? 0) + 1;
    return acc;
  },
  /** @type {Record<string, number>} */ ({}),
);

const latestLive = docs
  .filter((doc) => doc.id === 'backend/live-verification')
  .map((doc) => doc.date)
  .find(Boolean);

function normalizedType(doc) {
  if (doc.type !== 'verified') {
    return doc.type;
  }
  return doc.sources.some((source) => /supabase|vercel|live/i.test(source))
    ? 'verified-live'
    : 'verified-source';
}

const normalizedCounts = docs.reduce(
  (acc, doc) => {
    const type = normalizedType(doc);
    acc[type] = (acc[type] ?? 0) + 1;
    return acc;
  },
  /** @type {Record<string, number>} */ ({}),
);

mkdirSync(join(process.cwd(), 'src/generated'), {recursive: true});
writeFileSync(
  outputFile,
  `// Generated by scripts/generate-doc-status.mjs. Do not edit by hand.
export type DocumentationStatusType = 'verified' | 'partial' | 'open-question';

export interface DocumentationStatusEntry {
  id: string;
  title: string;
  type: DocumentationStatusType;
  date: string | null;
  sources: readonly string[];
}

export const documentationStatus = ${JSON.stringify(docs, null, 2)} as const satisfies readonly DocumentationStatusEntry[];

export const documentationStatusSummary = {
  total: ${docs.length},
  verified: ${counts.verified ?? 0},
  verifiedLive: ${normalizedCounts['verified-live'] ?? 0},
  verifiedSource: ${normalizedCounts['verified-source'] ?? 0},
  partial: ${counts.partial ?? 0},
  openQuestion: ${counts['open-question'] ?? 0},
  latestLiveBackendVerification: ${JSON.stringify(latestLive ?? null)},
} as const;
`,
);
